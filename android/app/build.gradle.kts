// Window transitions load XML resources in system_server, so their destinations
// cannot be supplied as runtime floats. Generate a 2%-spaced grid (at most 1% error on
// either axis) and keep typed references so release resource shrinking is safe.
val homeReturnOutput = layout.buildDirectory.dir("generated/homeReturn")
val generateHomeReturnAnimations by tasks.registering {
    outputs.dir(homeReturnOutput)
    doLast {
        val root = homeReturnOutput.get().asFile
        root.deleteRecursively()
        val anim = root.resolve("res/anim").apply { mkdirs() }
        val steps = 50
        val names = mutableListOf<String>()
        for (y in 0..steps) for (x in 0..steps) {
            val name = "home_return_${x}_${y}"
            names += name
            anim.resolve("$name.xml").writeText("""
                <set xmlns:android="http://schemas.android.com/apk/res/android"
                    android:shareInterpolator="false" android:zAdjustment="top">
                    <!-- ScaleAnimation resolves dimension endpoints against its actual
                         window size: both axes arrive at an icon-sized square.
                         Keep scale before translate so travel stays unscaled. -->
                    <scale android:fromXScale="1" android:toXScale="60dp"
                        android:fromYScale="1" android:toYScale="60dp"
                        android:pivotX="50%" android:pivotY="50%"
                        android:duration="550" android:interpolator="@interpolator/home_return_ease" />
                    <translate android:fromXDelta="0%p" android:toXDelta="${x * 2 - 50}%p"
                        android:fromYDelta="0%p" android:toYDelta="${y * 2 - 50}%p"
                        android:duration="550" android:interpolator="@interpolator/home_return_travel" />
                    <alpha android:fromAlpha="1" android:toAlpha="0"
                        android:startOffset="340" android:duration="170"
                        android:interpolator="@android:interpolator/fast_out_slow_in" />
                </set>
            """.trimIndent())
        }
        root.resolve("java/com/vincenthu/launcher/HomeReturnAnimationResources.java").apply {
            parentFile.mkdirs()
            writeText("""
                package com.vincenthu.launcher;
                // Generated by generateHomeReturnAnimations. Do not edit.
                final class HomeReturnAnimationResources {
                    static final int STEPS = $steps;
                    private static final int[] IDS = {${names.joinToString(",") { "R.anim.$it" }}};
                    static int exitFor(int index) { return IDS[index]; }
                }
            """.trimIndent())
        }
    }
}

